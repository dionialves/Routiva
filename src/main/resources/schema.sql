ALTER TABLE ping_sample
ADD COLUMN IF NOT EXISTS rtt_ns BIGINT;

ALTER TABLE ping_sample
ADD COLUMN IF NOT EXISTS collection_status VARCHAR(32);

ALTER TABLE ping_sample
ADD COLUMN IF NOT EXISTS error_code VARCHAR(255);

CREATE UNIQUE INDEX IF NOT EXISTS idx_ping_attempt ON ping_sample (collector_id, attempt_id);

CREATE INDEX IF NOT EXISTS idx_ping_batch ON ping_sample (collector_id, batch_id);

CREATE TABLE IF NOT EXISTS collector_batch (
    collector_id VARCHAR(64) NOT NULL,
    batch_id BIGINT NOT NULL,
    committed_at BIGINT NOT NULL,
    PRIMARY KEY (collector_id, batch_id)
);

-- All application writers acquire this row before allocating ping IDs.
-- A reader acquires it briefly to capture a boundary containing only committed writes.
CREATE TABLE IF NOT EXISTS ping_ingestion_guard (
    id INTEGER PRIMARY KEY CHECK (id = 1)
);
INSERT INTO ping_ingestion_guard(id)
SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM ping_ingestion_guard WHERE id = 1);

-- Durable progress and additive minute summaries.
CREATE TABLE IF NOT EXISTS ping_aggregation_progress (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    cursor_id BIGINT NOT NULL DEFAULT 0,
    boundary_id BIGINT NOT NULL DEFAULT 0,
    processed_at BIGINT,
    complete_through BIGINT NOT NULL DEFAULT 0
);
INSERT INTO ping_aggregation_progress(id)
SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM ping_aggregation_progress WHERE id=1);

CREATE TABLE IF NOT EXISTS ping_minute (
    host_id VARCHAR(255) NOT NULL,
    target VARCHAR(255) NOT NULL,
    minute_at BIGINT NOT NULL,
    total_pings BIGINT NOT NULL,
    healthy BIGINT NOT NULL,
    degraded BIGINT NOT NULL,
    lost BIGINT NOT NULL,
    errors BIGINT NOT NULL,
    latency_sum DOUBLE PRECISION NOT NULL,
    last_sample_at BIGINT NOT NULL,
    PRIMARY KEY(host_id, target, minute_at)
);
CREATE INDEX IF NOT EXISTS idx_ping_minute_time ON ping_minute(minute_at);

CREATE TABLE IF NOT EXISTS zabbix_settings (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    payload TEXT NOT NULL
);

-- Retired tables: drop dependents first, without CASCADE, preserving active data.
-- Idempotent on fresh databases and on subsequent application starts.
DROP TABLE IF EXISTS analytics_checkpoint_part;
DROP TABLE IF EXISTS analytics_checkpoint;
DROP TABLE IF EXISTS analytics_checkpoint_block;
DROP TABLE IF EXISTS analytics_checkpoint_guard;
DROP TABLE IF EXISTS host_latency_policy;

-- Rebuildable accelerators; ping_minute remains the durable source of truth.
CREATE TABLE IF NOT EXISTS ping_rollup (
    host_id VARCHAR(255) NOT NULL,
    target VARCHAR(255) NOT NULL,
    resolution BIGINT NOT NULL,
    bucket_at BIGINT NOT NULL,
    total_pings BIGINT NOT NULL,
    healthy BIGINT NOT NULL,
    degraded BIGINT NOT NULL,
    lost BIGINT NOT NULL,
    errors BIGINT NOT NULL,
    latency_sum DOUBLE PRECISION NOT NULL,
    last_sample_at BIGINT NOT NULL,
    valid_minutes BIGINT NOT NULL,
    PRIMARY KEY(host_id, target, resolution, bucket_at)
);
CREATE INDEX IF NOT EXISTS idx_ping_rollup_time ON ping_rollup(resolution, bucket_at);
ALTER TABLE ping_aggregation_progress ADD COLUMN IF NOT EXISTS rollups_ready BOOLEAN NOT NULL DEFAULT FALSE;

-- Last fully built dashboard generation, compressed JSON (gzip/base64).
-- Database replacement commits before the in-memory generation is published.
CREATE TABLE IF NOT EXISTS availability_snapshot (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    format_version INTEGER NOT NULL,
    built_at BIGINT NOT NULL,
    payload TEXT NOT NULL
);

-- Additive corrections committed with minute summaries; revision is the ingestion cursor.
CREATE TABLE IF NOT EXISTS availability_change (
    revision BIGINT NOT NULL,
    host_id VARCHAR(255) NOT NULL,
    target VARCHAR(255) NOT NULL,
    minute_at BIGINT NOT NULL,
    healthy BIGINT NOT NULL,
    degraded BIGINT NOT NULL,
    lost BIGINT NOT NULL,
    errors BIGINT NOT NULL,
    latency_sum DOUBLE PRECISION NOT NULL,
    last_sample_at BIGINT NOT NULL,
    valid_minutes BIGINT NOT NULL,
    PRIMARY KEY(revision, host_id, target, minute_at)
);
CREATE TABLE IF NOT EXISTS availability_change_state (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    floor_revision BIGINT NOT NULL
);
-- Existing snapshots older than this floor require one controlled rebuild on upgrade.
INSERT INTO availability_change_state(id,floor_revision)
SELECT 1,cursor_id FROM ping_aggregation_progress
WHERE id=1 AND NOT EXISTS (SELECT 1 FROM availability_change_state WHERE id=1);

-- Optional extremes: historical minutes without complete extrema remain unknown.
ALTER TABLE ping_minute ADD COLUMN IF NOT EXISTS latency_min DOUBLE PRECISION;
ALTER TABLE ping_minute ADD COLUMN IF NOT EXISTS latency_max DOUBLE PRECISION;

ALTER TABLE collector_batch ADD COLUMN IF NOT EXISTS rejection VARCHAR(255);

-- Split legacy raw ID migration from the live summary revision, initialized once on upgrade.
ALTER TABLE ping_aggregation_progress ADD COLUMN IF NOT EXISTS raw_cursor_id BIGINT;
UPDATE ping_aggregation_progress SET raw_cursor_id=cursor_id WHERE raw_cursor_id IS NULL;

-- Bounded receipt retention follows this order without scanning all receipts.
CREATE INDEX IF NOT EXISTS idx_collector_batch_retention
ON collector_batch(committed_at, collector_id, batch_id);

CREATE TABLE IF NOT EXISTS network_map (
    id VARCHAR(36) PRIMARY KEY,
    revision BIGINT NOT NULL,
    layout TEXT NOT NULL
);

ALTER TABLE network_map ADD COLUMN IF NOT EXISTS updated_at_ms BIGINT;
