CREATE TABLE IF NOT EXISTS ping_sample (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, host_id VARCHAR(255) NOT NULL, target VARCHAR(255) NOT NULL, measured_at BIGINT NOT NULL, latency DOUBLE PRECISION, error VARCHAR(255));
CREATE INDEX IF NOT EXISTS idx_ping_host_time ON ping_sample(host_id, target, measured_at);
CREATE INDEX IF NOT EXISTS idx_ping_time ON ping_sample(measured_at);

ALTER TABLE ping_sample ADD COLUMN IF NOT EXISTS latency_limit DOUBLE PRECISION NOT NULL DEFAULT 20;
CREATE TABLE IF NOT EXISTS host_latency_policy (host_id VARCHAR(255) PRIMARY KEY, latency_limit DOUBLE PRECISION NOT NULL CHECK (latency_limit > 0));
